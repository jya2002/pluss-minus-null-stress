export const developmentProject = "gawhbppuhnixqvhnnpnn";
export const developmentOrigin = `https://${developmentProject}.supabase.co`;
const uuid =
  /^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

function gmailBase(value) {
  const email = typeof value === "string" ? value.trim().toLowerCase() : "";
  const [local, domain] = email.split("@");
  if (
    domain !== "gmail.com" ||
    email.split("@").length !== 2 ||
    local.length > 30 ||
    !/^[a-z0-9]+(?:\.[a-z0-9]+)*$/.test(local)
  )
    throw new Error(
      "Configure a Gmail address you control, without a plus tag.",
    );
  return email;
}

export function fixtureEmail(emailBase, runId, label) {
  const base = gmailBase(emailBase);
  if (!uuid.test(runId) || !["a", "b", "c", "board", "admin"].includes(label))
    throw new Error("Invalid fixture run or label.");
  const [local, domain] = base.split("@");
  // Never shorten the mailbox name: that could address another person's inbox.
  // Twenty run-ID hex digits leave room for Gmail's longest username and role
  // under the email local-part limit (30 + 6 + 20 + 1 + 5 = 62 <= 64).
  const tag = runId.replaceAll("-", "").slice(0, 20).toLowerCase();
  return `${local}+pmns-${tag}-${label}@${domain}`;
}

export function validateConfiguration(env) {
  if (env.VITE_SUPABASE_URL?.replace(/\/$/, "") !== developmentOrigin)
    throw new Error("Only the pinned development project is allowed.");
  const publicKey = env.VITE_SUPABASE_PUBLISHABLE_KEY;
  const secretKey = env.PMNS_TEST_SERVICE_ROLE_KEY;
  function legacyRole(key, role) {
    try {
      const payload = JSON.parse(
        Buffer.from(key.split(".")[1], "base64url").toString(),
      );
      return payload.role === role && payload.ref === developmentProject;
    } catch {
      return false;
    }
  }
  if (
    typeof publicKey !== "string" ||
    !(publicKey.startsWith("sb_publishable_") || legacyRole(publicKey, "anon"))
  )
    throw new Error(
      "A publishable key or matching legacy anon key is required.",
    );
  if (
    typeof secretKey !== "string" ||
    !(
      secretKey.startsWith("sb_secret_") ||
      legacyRole(secretKey, "service_role")
    )
  )
    throw new Error(
      "A server secret or matching legacy service_role key is required.",
    );
  const emailBase = gmailBase(env.PMNS_TEST_EMAIL_BASE);
  return {
    url: developmentOrigin,
    key: publicKey,
    serviceKey: secretKey,
    emailBase,
  };
}

// The SDK cannot redirect credentials to another origin or follow an HTTP
// redirect. Cleanup uses a separate transport so interrupting the run does not
// abort its finally block. Timeout applies to each individual request.
export function pinnedFetch(signal, transport = globalThis.fetch) {
  return (input, init = {}) => {
    const url = new URL(
      typeof input === "string" || input instanceof URL ? input : input.url,
    );
    if (url.origin !== developmentOrigin || url.username || url.password)
      throw new Error(
        "Request outside the pinned development project blocked.",
      );
    return transport(input, {
      ...init,
      redirect: "error",
      signal: AbortSignal.any([
        AbortSignal.timeout(20000),
        ...(signal ? [signal] : []),
        ...(init.signal ? [init.signal] : []),
      ]),
    });
  };
}

// No table-wide deletes, account listing, email matching or audit-log deletion.
// All IDs are generated by this process, and remote ownership must also match.
export async function cleanupFixtures(service, manifest) {
  let verifiedAliases;
  try {
    verifiedAliases =
      Array.isArray(manifest.users) &&
      manifest.users.every(
        (user) =>
          user.email ===
          fixtureEmail(manifest.emailBase, manifest.runId, user.label),
      );
    // Also validate the base when setup stopped before any users were created.
    gmailBase(manifest.emailBase);
  } catch {
    return { complete: false, failures: ["invalid-manifest"] };
  }
  if (
    manifest.project !== developmentProject ||
    !uuid.test(manifest.runId) ||
    manifest.testTitle !== `[AUTOTEST ${manifest.runId}] Påmelding` ||
    !Array.isArray(manifest.users) ||
    !Array.isArray(manifest.events) ||
    !verifiedAliases ||
    manifest.users.some((user) => !uuid.test(user.id)) ||
    manifest.events.some(
      (event) =>
        !uuid.test(event.id) ||
        !manifest.users.some((user) => user.id === event.createdBy),
    )
  ) {
    return { complete: false, failures: ["invalid-manifest"] };
  }
  const failures = [];
  const ownedUsers = new Set();
  for (const fixture of manifest.users) {
    try {
      const { data, error } = await service.auth.admin.getUserById(fixture.id);
      if (error?.status === 404) continue;
      if (
        error ||
        data.user?.id !== fixture.id ||
        data.user.app_metadata?.pmns_test_run !== manifest.runId ||
        data.user.email !== fixture.email
      ) {
        failures.push(fixture.id);
      } else ownedUsers.add(fixture.id);
    } catch {
      failures.push(fixture.id);
    }
  }
  for (const fixture of manifest.events) {
    try {
      if (!ownedUsers.has(fixture.createdBy)) {
        failures.push(fixture.id);
        continue;
      }
      const { data, error } = await service
        .from("events")
        .select("id,title,is_demo,created_by")
        .eq("id", fixture.id)
        .maybeSingle();
      if (error) {
        failures.push(fixture.id);
        continue;
      }
      if (!data) continue;
      if (
        data.id !== fixture.id ||
        data.title !== manifest.testTitle ||
        data.is_demo !== true ||
        data.created_by !== fixture.createdBy
      ) {
        failures.push(fixture.id);
        continue;
      }
      const removed = await service
        .from("events")
        .delete()
        .eq("id", fixture.id)
        .eq("title", manifest.testTitle)
        .eq("is_demo", true)
        .eq("created_by", fixture.createdBy)
        .select("id");
      if (removed.error || removed.data?.length !== 1)
        failures.push(fixture.id);
    } catch {
      failures.push(fixture.id);
    }
  }
  // Do not cascade-delete accounts while an event could not be verified or
  // removed. Preserve all remaining fixtures for a reviewed recovery instead.
  if (failures.length)
    return {
      complete: false,
      failures: [...new Set([...failures, ...ownedUsers])],
    };
  for (const id of ownedUsers) {
    try {
      // A changed/unremoved event is retained together with its creator, so the
      // user cascade cannot silently alter that event's created_by field.
      const remaining = await service
        .from("events")
        .select("id")
        .eq("created_by", id)
        .limit(1);
      if (remaining.error || remaining.data?.length) {
        failures.push(id);
        continue;
      }
      const role = await service
        .from("user_roles")
        .update({ role: "student" })
        .eq("user_id", id)
        .select("user_id");
      if (role.error || role.data?.length !== 1) {
        failures.push(id);
        continue;
      }
      const removed = await service.auth.admin.deleteUser(id);
      if (removed.error) failures.push(id);
    } catch {
      failures.push(id);
    }
  }
  return { complete: failures.length === 0, failures: [...new Set(failures)] };
}
